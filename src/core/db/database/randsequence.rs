//! Randsequence productions (IEEE 1800-2009 18.17).
//!
//! A `randsequence` statement owns its productions. Every production, rule
//! and production-list element is a [`NodeKind::Production`] node; formals,
//! result variables and rule implicit variables (18.17.7) are ordinary
//! automatic [`NodeKind::Var`] nodes, and the assignments that bind formals
//! and copy results are ordinary assignment expressions, so consumers lower
//! them like any other procedural code.

use super::*;

/// One randsequence node.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ProductionKind {
    /// A production declaration (18.17). Boxed, like [`Self::Rule`], to
    /// keep [`NodeKind`] compact.
    Declaration(Box<ProductionDecl>),
    /// One `|`-separated rule of a production (18.17.1).
    Rule(Box<ProductionRule>),
    /// A generation of a production with bound arguments (18.17.6).
    Item(ProductionItem),
    /// A `{ ... }` code block (18.17.2); `body` is its statement.
    CodeBlock { body: NodeId },
    /// `if (condition) item [else item]` (18.17.3).
    If {
        condition: NodeId,
        then_item: NodeId,
        else_item: Option<NodeId>,
    },
    /// `repeat (count) item` (18.17.3).
    Repeat { count: NodeId, item: NodeId },
    /// `case (selector) ... endcase` (18.17.3). Items keep source order.
    Case {
        selector: NodeId,
        items: Vec<ProductionCaseItem>,
        default: Option<NodeId>,
    },
}

/// A production declaration.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProductionDecl {
    /// Formal arguments, as automatic variables, in declaration order.
    pub formals: Vec<NodeId>,
    /// A reference expression to each formal, in the same order.
    pub formal_refs: Vec<NodeId>,
    /// Per formal: `true` when its direction is not `input`. Formals past
    /// the 63rd share one flag, so this is conservative for them.
    pub non_input: Vec<bool>,
    /// The automatic variable that holds a non-void production's `return`
    /// value, and an assignable reference to it.
    pub result: Option<ProductionResult>,
    /// Rules in source order.
    pub rules: Vec<NodeId>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ProductionResult {
    pub variable: NodeId,
    pub reference: NodeId,
    /// Assignment that resets the variable to its type's default from a
    /// never-written automatic variable (a child of the production).
    pub reset: NodeId,
}

/// One rule: a production list, its weight and implicit variables.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProductionRule {
    /// Production-list elements in source order: items, code blocks, `if`,
    /// `repeat` and `case` nodes.
    pub elements: Vec<NodeId>,
    /// The `:=` weight expression.
    pub weight: Option<NodeId>,
    /// The weight clause's code block, run after the production list.
    pub weight_code: Option<NodeId>,
    /// Implicit variables of the non-void productions the rule generates.
    pub variables: Vec<NodeId>,
    /// The assignment that resets each implicit variable (same order), as
    /// for [`ProductionResult::reset`].
    pub resets: Vec<NodeId>,
    /// `Some` for a `rand join` rule; the inner value is its optional
    /// real expression (18.17.5).
    pub rand_join: Option<Option<NodeId>>,
}

/// A generation of `production`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProductionItem {
    /// The generated production; `None` only for an unresolved name.
    pub production: Option<NodeId>,
    /// Assignments of actual (or default) values to input formals.
    pub bindings: Vec<ProductionBinding>,
    /// The assignment of the production's result to this occurrence's
    /// implicit variable, for a non-void production generated by a rule.
    pub result_copy: Option<NodeId>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ProductionBinding {
    pub formal: usize,
    pub assignment: NodeId,
}

/// One case production item: its expressions and the item it generates.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProductionCaseItem {
    pub exprs: Vec<NodeId>,
    pub item: NodeId,
}

impl ProductionKind {
    pub(crate) fn referenced_nodes(&self, refs: &mut Vec<NodeId>) {
        match self {
            ProductionKind::Declaration(decl) => {
                refs.extend(decl.formals.iter().copied());
                refs.extend(decl.formal_refs.iter().copied());
                if let Some(result) = decl.result {
                    refs.extend([result.variable, result.reference, result.reset]);
                }
                refs.extend(decl.rules.iter().copied());
            }
            ProductionKind::Rule(rule) => {
                refs.extend(rule.elements.iter().copied());
                refs.extend(rule.weight);
                refs.extend(rule.weight_code);
                refs.extend(rule.variables.iter().copied());
                refs.extend(rule.resets.iter().copied());
                refs.extend(rule.rand_join.flatten());
            }
            ProductionKind::Item(item) => {
                refs.extend(item.production);
                refs.extend(item.bindings.iter().map(|binding| binding.assignment));
                refs.extend(item.result_copy);
            }
            ProductionKind::CodeBlock { body } => refs.push(*body),
            ProductionKind::If {
                condition,
                then_item,
                else_item,
            } => {
                refs.extend([*condition, *then_item]);
                refs.extend(*else_item);
            }
            ProductionKind::Repeat { count, item } => refs.extend([*count, *item]),
            ProductionKind::Case {
                selector,
                items,
                default,
            } => {
                refs.push(*selector);
                for item in items {
                    refs.extend(item.exprs.iter().copied());
                    refs.push(item.item);
                }
                refs.extend(*default);
            }
        }
    }
}

pub(super) fn production_from_slang(
    node: &SemanticNode,
    edges: &[crate::ffi::slang::SemanticEdge],
    ids: &SemanticIds,
) -> Result<NodeKind, DbError> {
    use crate::ffi::slang::{
        PRODUCTION_RULE_RAND_JOIN, SEMANTIC_PRODUCTION_CASE, SEMANTIC_PRODUCTION_CODE_BLOCK,
        SEMANTIC_PRODUCTION_DECLARATION, SEMANTIC_PRODUCTION_IF, SEMANTIC_PRODUCTION_ITEM,
        SEMANTIC_PRODUCTION_REPEAT, SEMANTIC_PRODUCTION_RULE,
    };
    let required = |role, what: &str| {
        edge_target(ids, edges, role)?.ok_or_else(|| {
            DbError::InvalidSnapshot(format!("randsequence {} has no {what}", node.detail))
        })
    };
    let kind = match node.subkind {
        SEMANTIC_PRODUCTION_DECLARATION => {
            let formals =
                ordered_targets(ids, edges, SemanticEdgeRole::Argument, "production formal")?;
            let formal_refs =
                ordered_targets(ids, edges, SemanticEdgeRole::Operand, "production formal")?;
            if formal_refs.len() != formals.len() {
                return Err(DbError::InvalidSnapshot(
                    "production formal references disagree with its formals".into(),
                ));
            }
            let non_input = (0..formals.len())
                .map(|index| node.auxiliary & (1u64 << index.min(63)) != 0)
                .collect();
            let result = match (
                edge_target(ids, edges, SemanticEdgeRole::Declaration)?,
                edge_target(ids, edges, SemanticEdgeRole::Lhs)?,
                edge_target(ids, edges, SemanticEdgeRole::DefaultValue)?,
            ) {
                (Some(variable), Some(reference), Some(reset)) => Some(ProductionResult {
                    variable,
                    reference,
                    reset,
                }),
                (None, None, None) => None,
                _ => {
                    return Err(DbError::InvalidSnapshot(
                        "production result variable and reference disagree".into(),
                    ))
                }
            };
            ProductionKind::Declaration(Box::new(ProductionDecl {
                formals,
                formal_refs,
                non_input,
                result,
                rules: ordered_targets(ids, edges, SemanticEdgeRole::Branch, "production rule")?,
            }))
        }
        SEMANTIC_PRODUCTION_RULE => {
            let variables = ordered_targets(
                ids,
                edges,
                SemanticEdgeRole::Declaration,
                "rule implicit variable",
            )?;
            let resets = ordered_targets(
                ids,
                edges,
                SemanticEdgeRole::Initializer,
                "rule implicit variable reset",
            )?;
            if resets.len() != variables.len() {
                return Err(DbError::InvalidSnapshot(
                    "rule implicit variable resets disagree with its variables".into(),
                ));
            }
            ProductionKind::Rule(Box::new(ProductionRule {
                elements: ordered_targets(ids, edges, SemanticEdgeRole::Operand, "rule element")?,
                weight: edge_target(ids, edges, SemanticEdgeRole::Weight)?,
                weight_code: edge_target(ids, edges, SemanticEdgeRole::Body)?,
                variables,
                resets,
                rand_join: (node.auxiliary & PRODUCTION_RULE_RAND_JOIN != 0)
                    .then(|| edge_target(ids, edges, SemanticEdgeRole::RandJoin))
                    .transpose()?,
            }))
        }
        SEMANTIC_PRODUCTION_ITEM => {
            let mut bindings = edges
                .iter()
                .filter(|edge| edge.role == SemanticEdgeRole::Argument)
                .map(|edge| {
                    Ok(ProductionBinding {
                        formal: edge.index as usize,
                        assignment: semantic_id(ids, edge.target_id)?,
                    })
                })
                .collect::<Result<Vec<_>, DbError>>()?;
            bindings.sort_by_key(|binding| binding.formal);
            if bindings
                .windows(2)
                .any(|pair| pair[0].formal == pair[1].formal)
            {
                return Err(DbError::InvalidSnapshot(
                    "production item binds a formal twice".into(),
                ));
            }
            ProductionKind::Item(ProductionItem {
                production: edge_target(ids, edges, SemanticEdgeRole::Callee)?,
                bindings,
                result_copy: edge_target(ids, edges, SemanticEdgeRole::Rhs)?,
            })
        }
        SEMANTIC_PRODUCTION_CODE_BLOCK => ProductionKind::CodeBlock {
            body: required(SemanticEdgeRole::Body, "statement")?,
        },
        SEMANTIC_PRODUCTION_IF => ProductionKind::If {
            condition: required(SemanticEdgeRole::Condition, "condition")?,
            then_item: required(SemanticEdgeRole::Then, "item")?,
            else_item: edge_target(ids, edges, SemanticEdgeRole::Else)?,
        },
        SEMANTIC_PRODUCTION_REPEAT => ProductionKind::Repeat {
            count: required(SemanticEdgeRole::Condition, "count")?,
            item: required(SemanticEdgeRole::Body, "item")?,
        },
        SEMANTIC_PRODUCTION_CASE => {
            let item_nodes =
                ordered_targets(ids, edges, SemanticEdgeRole::Branch, "case production item")?;
            let mut items = item_nodes
                .into_iter()
                .map(|item| ProductionCaseItem {
                    exprs: Vec::new(),
                    item,
                })
                .collect::<Vec<_>>();
            let mut exprs = edges
                .iter()
                .filter(|edge| edge.role == SemanticEdgeRole::CaseItem)
                .collect::<Vec<_>>();
            exprs.sort_by_key(|edge| edge.index);
            for edge in exprs {
                let item = items.get_mut((edge.index >> 16) as usize).ok_or_else(|| {
                    DbError::InvalidSnapshot("case production expression has no item".into())
                })?;
                if (edge.index & 0xffff) as usize != item.exprs.len() {
                    return Err(DbError::InvalidSnapshot(
                        "case production expression indices must be dense and unique".into(),
                    ));
                }
                item.exprs.push(semantic_id(ids, edge.target_id)?);
            }
            if items.iter().any(|item| item.exprs.is_empty()) {
                return Err(DbError::InvalidSnapshot(
                    "case production item has no expression".into(),
                ));
            }
            ProductionKind::Case {
                selector: required(SemanticEdgeRole::CaseExpression, "selector")?,
                items,
                default: edge_target(ids, edges, SemanticEdgeRole::Else)?,
            }
        }
        _ => {
            return Err(DbError::InvalidSnapshot(
                "randsequence node has an unknown subkind".into(),
            ))
        }
    };
    Ok(NodeKind::Production(kind))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn compile(source: &str) -> Db {
        let output = crate::core::compile::compile_sources_checked(
            &[crate::core::compile::OwnedSource::compilation_unit(
                "randsequence.sv",
                source,
            )],
            &crate::core::compile::CompileOpts {
                top: Some("tb".into()),
                ..Default::default()
            },
        )
        .unwrap();
        Db::from_slang(&output.snapshot).unwrap()
    }

    fn production(db: &Db, name: &str) -> (NodeId, ProductionDecl) {
        db.node_ids()
            .find_map(|id| match db.node_kind(id) {
                NodeKind::Production(ProductionKind::Declaration(decl))
                    if db.node(id).name == name =>
                {
                    Some((id, decl.as_ref().clone()))
                }
                _ => None,
            })
            .unwrap_or_else(|| panic!("production `{name}`"))
    }

    fn rule(db: &Db, id: NodeId) -> ProductionRule {
        match db.node_kind(id) {
            NodeKind::Production(ProductionKind::Rule(rule)) => rule.as_ref().clone(),
            other => panic!("rule expected, found {other:?}"),
        }
    }

    fn item(db: &Db, id: NodeId) -> ProductionItem {
        match db.node_kind(id) {
            NodeKind::Production(ProductionKind::Item(item)) => item.clone(),
            other => panic!("item expected, found {other:?}"),
        }
    }

    /// String constants displayed anywhere under `id`, in tree order.
    fn displayed(db: &Db, id: NodeId, out: &mut Vec<String>) {
        if let NodeKind::Expr(ExprKind::Constant {
            value: ValueData::Bytes(bytes),
            ..
        }) = db.node_kind(id)
        {
            out.push(String::from_utf8_lossy(bytes).into_owned());
        }
        for child in db.node(id).children() {
            if db.node(*child).parent() == Some(id) {
                displayed(db, *child, out);
            }
        }
    }

    #[test]
    fn productions_rules_and_elements_are_typed() {
        let db = compile(
            "module tb; int q[$]; initial begin static int n = 3; \
             randsequence (main) \
               main : first second(5) done jn ; \
               first : add := 2 | dec := n { $display(\"weight\"); } ; \
               second (int k) : if (k > 2) pop else push | repeat (2) pop ; \
               int pop : { return 7; } ; \
               int push : { q.push_back(1); return 3; } ; \
               done : case (n) 1, 2 : pop; default : push; endcase ; \
               jn : rand join (0.0) add dec ; \
               add : { $display(\"add\"); } ; \
               dec : { $display(\"dec\"); } ; \
             endsequence end endmodule",
        );
        let statement = db
            .node_ids()
            .find_map(|id| match db.node_kind(id) {
                NodeKind::Stmt(StmtKind::RandSequence { productions, top }) => {
                    Some((productions.clone(), *top))
                }
                _ => None,
            })
            .expect("randsequence statement");
        assert_eq!(statement.0.len(), 9);
        let (main, main_decl) = production(&db, "main");
        assert_eq!(statement.0[0], main);
        assert_eq!(item(&db, statement.1.unwrap()).production, Some(main));
        assert!(main_decl.result.is_none() && main_decl.formals.is_empty());

        let (_, first) = production(&db, "first");
        assert_eq!(first.rules.len(), 2);
        let weighted = rule(&db, first.rules[1]);
        assert!(weighted.weight.is_some() && weighted.weight_code.is_some());
        assert!(rule(&db, first.rules[0]).weight_code.is_none());

        // `second(5)` binds formal 0 by an assignment to the formal.
        let (second, second_decl) = production(&db, "second");
        assert_eq!(second_decl.formals.len(), 1);
        assert_eq!(second_decl.non_input, vec![false]);
        let main_rule = rule(&db, main_decl.rules[0]);
        let call = item(&db, main_rule.elements[1]);
        assert_eq!(call.production, Some(second));
        assert_eq!(call.bindings.len(), 1);
        assert_eq!(call.bindings[0].formal, 0);

        // A non-void production's result is copied to the rule's implicit
        // variable, one per generated non-void production.
        let (_, pop) = production(&db, "pop");
        let result = pop.result.expect("pop result");
        assert!(matches!(
            db.node_kind(result.variable),
            NodeKind::Var { .. }
        ));
        let NodeKind::Expr(ExprKind::Operation { operands, .. }) = db.node_kind(result.reset)
        else {
            panic!("result reset assignment");
        };
        assert!(matches!(
            db.node_kind(operands[0]),
            NodeKind::Expr(ExprKind::Ref { target: Some(target) }) if *target == result.variable
        ));
        assert_eq!(second_decl.formal_refs.len(), 1);
        let if_rule = rule(&db, second_decl.rules[0]);
        assert_eq!(if_rule.variables.len(), 2);
        assert_eq!(if_rule.resets.len(), 2);
        let NodeKind::Production(ProductionKind::If {
            then_item,
            else_item,
            ..
        }) = db.node_kind(if_rule.elements[0])
        else {
            panic!("if element");
        };
        assert!(item(&db, *then_item).result_copy.is_some());
        assert!(else_item.is_some());
        assert!(matches!(
            db.node_kind(rule(&db, second_decl.rules[1]).elements[0]),
            NodeKind::Production(ProductionKind::Repeat { .. })
        ));

        let (_, done) = production(&db, "done");
        let NodeKind::Production(ProductionKind::Case { items, default, .. }) =
            db.node_kind(rule(&db, done.rules[0]).elements[0])
        else {
            panic!("case element");
        };
        assert_eq!(items.len(), 1);
        assert_eq!(items[0].exprs.len(), 2);
        assert!(default.is_some());

        let (_, jn) = production(&db, "jn");
        let join = rule(&db, jn.rules[0]);
        assert!(matches!(join.rand_join, Some(Some(_))));
        assert_eq!(join.elements.len(), 2);
    }

    #[test]
    fn repeated_results_use_implicit_arrays_and_code_blocks_keep_their_syntax() {
        // Slang v11 attaches a weight-clause code block to the wrong element
        // when the rule also has a code block element; capture must keep
        // each block with its own statement.
        let db = compile(
            "module tb; initial randsequence (main) \
               main : val { $display(\"element\"); } val := 1 { $display(\"weight\"); } \
                    | val := 0 ; \
               int val : { return 1; } ; \
             endsequence endmodule",
        );
        let (_, main) = production(&db, "main");
        let first = rule(&db, main.rules[0]);
        assert_eq!(first.variables.len(), 1);
        assert_eq!(first.elements.len(), 3);
        let NodeKind::Production(ProductionKind::CodeBlock { body }) =
            db.node_kind(first.elements[1])
        else {
            panic!("element code block");
        };
        let mut element = Vec::new();
        displayed(&db, *body, &mut element);
        assert_eq!(element, ["element"]);
        let NodeKind::Production(ProductionKind::CodeBlock { body }) =
            db.node_kind(first.weight_code.expect("weight code block"))
        else {
            panic!("weight code block");
        };
        let mut weight = Vec::new();
        displayed(&db, *body, &mut weight);
        assert_eq!(weight, ["weight"]);
        // Two occurrences of `val` make its implicit variable an array whose
        // elements receive the copies.
        let copies = [first.elements[0], first.elements[2]]
            .map(|id| item(&db, id).result_copy.expect("result copy"));
        for copy in copies {
            let NodeKind::Expr(ExprKind::Operation { operands, .. }) = db.node_kind(copy) else {
                panic!("copy assignment");
            };
            assert!(matches!(
                db.node_kind(operands[0]),
                NodeKind::Expr(ExprKind::ArraySelect { .. })
            ));
        }
    }

    #[test]
    fn each_production_is_reached_once_through_the_children_tree() {
        // The productions are members of the statement's block scope, which
        // is itself a child of the enclosing statement and of the module.
        // Only the randsequence statement may own them as children, or tree
        // walks (lint, analyses) see every code block several times.
        let db = compile(
            "module tb; int n; initial begin \
               randsequence (main) \
                 main : step ; \
                 step : { n = 1; } ; \
               endsequence \
             end endmodule",
        );
        fn walk(db: &Db, id: NodeId, seen: &mut Vec<NodeId>) {
            seen.push(id);
            for child in db.node(id).children() {
                walk(db, *child, seen);
            }
        }
        let mut seen = Vec::new();
        for top in db.tops() {
            walk(&db, *top, &mut seen);
        }
        for name in ["main", "step"] {
            let (id, _) = production(&db, name);
            assert_eq!(seen.iter().filter(|seen| **seen == id).count(), 1, "{name}");
            assert!(matches!(
                db.node_kind(db.node(id).parent().expect("production parent")),
                NodeKind::Stmt(StmtKind::Begin)
            ));
        }
        let assignments = seen
            .iter()
            .filter(|id| matches!(db.node_kind(**id), NodeKind::Stmt(StmtKind::Assign { .. })))
            .count();
        assert_eq!(assignments, 1);
    }
}
